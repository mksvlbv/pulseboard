function generateReadings(baseTemp: number, baseHumidity: number, baseEnergy: number, basePressure: number) {
  const readings = [];
  const now = Date.now();
  for (let i = 23; i >= 0; i--) {
    readings.push({
      timestamp: now - i * 3600000,
      temperature: baseTemp + (Math.random() - 0.5) * 6,
      humidity: baseHumidity + (Math.random() - 0.5) * 10,
      energy: baseEnergy + (Math.random() - 0.5) * 0.8,
      pressure: basePressure + (Math.random() - 0.5) * 20,
    });
  }
  return readings;
}

